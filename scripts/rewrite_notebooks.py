"""Helper to build valid Jupyter notebooks from a list of cells."""
import json

def nb(*cells):
    """cells = list of (cell_type:str, source_lines:list[str], outputs:list, code)"""
    result = []
    for cell in cells:
        if len(cell) == 4:
            cell_type, source, outputs, execution_count = cell
        elif len(cell) == 3:
            cell_type, source, outputs = cell
            execution_count = None
        elif len(cell) == 2:
            cell_type, source = cell
            outputs = []
            execution_count = None
        c = {
            "cell_type": cell_type,
            "metadata": {},
            "source": source,
        }
        if cell_type == "code":
            c["execution_count"] = execution_count
            c["outputs"] = outputs or []
            c["metadata"] = {}
        result.append(c)
    return json.dumps({
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.13.0"},
        },
        "cells": result,
    }, indent=1, ensure_ascii=False)


def s(*lines):
    """Convert a list of strings to a notebook source list.
    Each line gets a \\n appended except the last.
    """
    return [line + "\n" for line in lines[:-1]] + [lines[-1]]


def code(*lines):
    return s(*lines)


def md(*lines):
    return s(*lines)


